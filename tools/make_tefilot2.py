def ashrei_node(nus):
    for n in T.SRC["shacharit"][nus]:
        if n["he"] == ["אשרי"]:
            return n
    raise SystemExit("אין אשרי בשחרית של " + nus)


def nodes_of(prayer, nus):
    nodes = list(S2[prayer][nus])
    if prayer == "mincha" and nus in ("em", "sef"):
        nodes.insert(1, ashrei_node(nus))          # אחרי הקרבנות ולפני העמידה, כמו בסדר המנחה
    if prayer == "arvit" and nus == "ash":
        skip = {"לדוד", "ברכת הלבנה", "קריאת שמע על המיטה", "תוספות למוצאי שבת"}
        nodes = [n for n in nodes if n["he"][0] not in skip]
    return nodes


