def seo_html(prayer, nus):
    I = INFO[prayer]
    N = T.SH[nus][2]
    sw = switch_text(prayer)
    out = ['<!--seo-txt-->\n<section class="k-sec seo-txt" aria-labelledby="seo-h">',
           f'  <h2 id="seo-h">{I["seo_h"]}</h2>']
    for ptxt in I["intro"]:
        out.append("  <p>" + ptxt.replace("{N}", N).replace("{SW}", sw) + "</p>")
    for h, ptxt in I["subs"]:
        out.append(f"  <h3>{h}</h3>\n  <p>{ptxt}</p>")
    out.append(f"  {KR}")
    out.append("</section>")
    faq = list(I["faq"]) + [COMMON_FAQ_NUS, COMMON_FAQ_SRC, COMMON_FAQ_READ]
    out.append(T.faq_html(faq))
    out.append("<!--/seo-txt-->")
    return "\n".join(out), faq


