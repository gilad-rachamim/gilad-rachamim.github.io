def card(href, title, desc, badge="לשחק"):
    return (f'    <a href="{href}"><span class="badge">{badge}</span><b>{title}</b>'
            f'<span>{desc}</span></a>')


def section(sid, h2, lead, cards):
    out = [f'<section class="k-sec" aria-labelledby="{sid}">', f'  <h2 id="{sid}">{h2}</h2>']
    if lead:
        out.append(f'  <p class="lead2">{lead}</p>')
    out.append('  <div class="dom">')
    out += [card(*c) for c in cards]
    out += ['  </div>', '</section>']
    return "\n".join(out)


def table(sid, h2, lead, head, rows):
    out = [f'<section class="k-sec" aria-labelledby="{sid}">', f'  <h2 id="{sid}">{h2}</h2>']
    if lead:
        out.append(f'  <p class="lead2">{lead}</p>')
    out.append(f'  <div class="cat-wrap" tabindex="0" role="region" aria-labelledby="{sid}"><table class="cat-tbl">')
    out.append("    <thead><tr>" + "".join(f"<th scope=\"col\">{h}</th>" for h in head) + "</tr></thead><tbody>")
    for r in rows:
        out.append("    <tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>")
    out += ["    </tbody></table></div>", "</section>"]
    return "\n".join(out)


def build(p):
    faq_ld = {"@context": "https://schema.org", "@type": "FAQPage", "mainEntity": [
        {"@type": "Question", "name": q, "acceptedAnswer": {"@type": "Answer", "text": a}} for q, a in p["faq"]]}
    meta = {
        "site": "kelim", "nav": "tchumim", "tool": "chashiva_cat_" + p["slug"].replace("-", "_"),
        "title": p["title"] + " | הכלים של גילעד רחמים",
        "description": p["description"], "og_title": p["og_title"], "priority": "0.7",
        "crumbs": [["משחקי חשיבה", G], [p["crumb"], None]],
        "head": '<link rel="stylesheet" href="/assets/chashiva.css"><link rel="stylesheet" href="/assets/seo-txt.css">'
                + CSS + '<script type="application/ld+json">' + json.dumps(faq_ld, ensure_ascii=False) + "</script>",
    }
    parts = ["<!--meta " + json.dumps(meta, ensure_ascii=False, indent=2) + " -->",
             '<header class="k-hero">', f'  <h1>{p["h1"]}</h1>', f'  <p class="sub">{p["sub"]}</p>', "</header>"]
    for i, s in enumerate(p["sections"]):
        if s[0] == "table":
            parts.append(table(f'cat-t{i}', *s[1:]))
        else:
            parts.append(section(f'cat-s{i}', *s))
    share = html.escape(p["share"], quote=True)
    parts.append(
        '<section class="k-sec" aria-labelledby="cat-share-h">\n'
        f'  <h2 id="cat-share-h">{p["share_h"]}</h2>\n'
        f'  <p class="lead2">{p["share_lead"]}</p>\n'
        f'  <div class="actions"><a class="btn btn-gold" href="#" data-share-tool="wa" data-text="{share}" target="_blank" rel="noopener">'
        '<svg class="ic"><use href="#wa"/></svg> לשלוח לחבר בווטסאפ</a>'
        f'<a class="btn btn-line" href="{G}">כל משחקי החשיבה</a><a class="btn btn-line" href="/kelim/bakasha/">רעיון למשחק</a></div>\n'
        "</section>")
    sib = [x for x in PAGES if x["slug"] != p["slug"]]
    parts.append(
        '<section class="k-sec" aria-labelledby="cat-sib-h">\n  <h2 id="cat-sib-h">עוד אוספי משחקים</h2>\n  <div class="dom">\n'
        + "\n".join(card(f'{G}{x["slug"]}/', x["crumb"], x["teaser"], "אוסף") for x in sib) + "\n  </div>\n</section>")
    seo = ["", "<!--seo-txt-->", '<section class="k-sec seo-txt" aria-labelledby="seo-h">', f'  <h2 id="seo-h">{p["seo_h2"]}</h2>']
    for blk in p["seo"]:
        if blk.startswith("## "):
            seo.append(f"  <h3>{blk[3:]}</h3>")
        else:
            seo.append(f"  <p>{blk}</p>")
    seo += ["</section>", '<section class="k-sec seo-faq" aria-labelledby="seo-faq-h">', '  <h2 id="seo-faq-h">שאלות ותשובות</h2>']
    seo += [f"  <details><summary>{q}</summary><p>{a}</p></details>" for q, a in p["faq"]]
    seo += ["</section>", "<!--/seo-txt-->", ""]
    return "\n".join(parts + seo)


