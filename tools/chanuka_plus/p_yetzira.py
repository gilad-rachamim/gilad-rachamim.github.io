AGES = {'3-5': 'גיל גן (3 עד 5)', '6-9': 'גיל בית ספר (6 עד 9)', '10+': 'גיל 10 ומעלה'}


def craft_cards():
    out = []
    for cid, name, age, mins, desc, mats, steps, safe in CRAFTS:
        tmpl = ''
        key = {'tmpl-dreidel': 'dreidel', 'tmpl-chanukiya': 'chanukiya', 'tmpl-pach': 'pach', 'tmpl-garland': 'garland'}.get(cid)
        if key:
            tmpl = '<p><button type="button" class="btn btn-gold yz-open" data-t="%s">להציג ולהדפיס את התבנית</button></p>' % key
        out.append(
            '<article class="yz-card" id="%s" data-age="%s" data-min="%d"><h3>%s</h3><div class="yz-meta"><span>%s</span><span>%d דקות</span></div><p>%s</p>'
            '<b>חומרים</b><ul>%s</ul><b>שלבים</b><ol>%s</ol>%s<p class="yz-safe">בטיחות: %s</p></article>'
            % (cid, age, mins, name, AGES[age], mins, desc, ''.join('<li>%s</li>' % m for m in mats), ''.join('<li>%s</li>' % s for s in steps), tmpl, safe))
    return ''.join(out)


