def strip(html):
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", "", html)).strip()


def faq_html(faq):
    return ('<section class="k-sec seo-faq" aria-labelledby="seo-faq-h">\n  <h2 id="seo-faq-h">שאלות ותשובות</h2>\n'
            + "\n".join(f"  <details><summary>{q}</summary><p>{a}</p></details>" for q, a in faq) + "\n</section>")


def page(path, meta, body, faq, app):
    graph = [{"@type": "FAQPage", "mainEntity": [
        {"@type": "Question", "name": q, "acceptedAnswer": {"@type": "Answer", "text": strip(a)}} for q, a in faq]}]
    # WebApplication לא כאן: build.py מוסיף אחד לכל דף כלי (שניים = כפילות בסכמה)
    ld = json.dumps({"@context": "https://schema.org", "@graph": graph}, ensure_ascii=False)
    meta = dict(meta)
    meta["head"] = ('<link rel="stylesheet" href="/assets/seo-txt.css"><link rel="stylesheet" href="/assets/miluim-gibush.css">'
                    f'<script type="application/ld+json">{ld}</script>')
    out = "<!--meta " + json.dumps(meta, ensure_ascii=False, indent=2) + " -->\n" + body.strip() + "\n" + faq_html(faq) + "\n<!--/seo-txt-->\n"
    p = BASE / path / "index.html"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(out, encoding="utf-8", newline="\n")
    words = len(strip(out.split("<!--seo-txt-->")[-1]).split()) if "<!--seo-txt-->" in out else 0
    print(p.relative_to(ROOT), "· מילים בבלוק הטקסט:", words, "· שאלות:", len(faq))


