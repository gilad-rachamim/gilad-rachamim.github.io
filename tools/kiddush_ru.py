def block(kid, who, tr, ex, resp, note):
    out = [f'<div class="kd-b" id="{kid}">', f'<p class="kd-who">{who}</p>',
           f'<p class="kd-he" lang="he" dir="rtl">{HE[kid]}</p>',
           f'<p class="kd-tr"><span class="kd-k">Говорите:</span> {tr}</p>',
           f'<p class="kd-en"><span class="kd-k">Смысл:</span> {ex}</p>']
    if note:
        out.append(f'<p class="kd-note">{note}</p>')
    if resp:
        out.append(f'<p class="kd-resp"><span class="kd-k">Все отвечают:</span> <b>{resp}</b></p>')
    out.append("</div>")
    return "\n".join(out)


