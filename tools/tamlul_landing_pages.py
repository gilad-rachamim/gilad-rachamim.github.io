def esc(s):
    return html.escape(s, quote=False)


def buttons(p, where):
    tool = f'<a class="btn {{c1}}" href="{TOOL}" data-mv="tamlul_{p["slug"]}_tool">🎙 לתמלל עכשיו באתר</a>'
    bot = (f'<a class="btn {{c2}}" href="{BOT}{p["slug"]}" target="_blank" rel="noopener" data-bot="tamlul" '
           f'data-mv="tamlul_{p["slug"]}_bot">🤖 לפתוח את הבוט בטלגרם</a>')
    if p["first"] == "bot":
        return bot.format(c2="btn-gold") + tool.format(c1="btn-line")
    return tool.format(c1="btn-gold") + bot.format(c2="btn-line")


def page(p):
    faq_ld = {"@context": "https://schema.org", "@type": "FAQPage", "mainEntity": [
        {"@type": "Question", "name": q, "acceptedAnswer": {"@type": "Answer", "text": a}} for q, a in p["faq"]]}
    head = STYLE + '<script type="application/ld+json">' + json.dumps(faq_ld, ensure_ascii=False) + "</script>"
    meta = {"site": "kelim", "nav": "tamlul", "tool": "tamlul_" + p["slug"], "title": p["title"], "description": p["desc"],
            "og_title": p["og"], "priority": "0.7", "crumbs": [["תמלול", TOOL], [p["crumb"], None]], "head": head}
    o = ["<!--meta " + json.dumps(meta, ensure_ascii=False, indent=2) + " -->",
         '<header class="k-hero tlp-hero">',
         f'  <h1>{esc(p["h1"])}</h1>',
         f'  <p class="sub">{esc(p["sub"])}</p>',
         f'  <div class="actions">{buttons(p, "top")}</div>',
         "</header>",
         '<section class="k-sec tlp-sec" aria-labelledby="tlp-how">',
         f'  <h2 id="tlp-how">{esc(p["how_h"])}</h2>',
         '  <ol class="tlp-steps">']
    o += [f"    <li><span>{s}</span></li>" for s in p["steps"]]
    o += ["  </ol>", "</section>"]
    for i, (h, paras) in enumerate(p["secs"], start=1):
        o += [f'<section class="k-sec tlp-sec" aria-labelledby="tlp-s{i}">', f'  <h2 id="tlp-s{i}">{esc(h)}</h2>']
        o += [f"  <p>{t}</p>" for t in paras]
        o.append("</section>")
    o += ['<section class="k-sec tlp-sec" aria-labelledby="tlp-why">', '  <h2 id="tlp-why">למה זה בחינם</h2>', f"  <p>{WHY}</p>", "</section>",
          '<section class="k-sec" aria-labelledby="faq-h">', '  <h2 id="faq-h">שאלות ותשובות</h2>']
    o += [f"  <details><summary>{esc(q)}</summary><p>{esc(a)}</p></details>" for q, a in p["faq"]]
    o += ["</section>",
          '<section class="k-sec tlp-end" aria-labelledby="tlp-go">',
          '  <h2 id="tlp-go">מתחילים?</h2>',
          f'  <div class="actions" style="justify-content:center">{buttons(p, "end")}'
          f'<a class="btn btn-line" href="#" data-share-tool="wa" data-text="{html.escape(p["share"])}" target="_blank" rel="noopener">'
          '<svg class="ic"><use href="#wa"/></svg> לשלוח לחבר שצריך את זה</a></div>',
          "</section>"]
    return "\n".join(o) + "\n"


